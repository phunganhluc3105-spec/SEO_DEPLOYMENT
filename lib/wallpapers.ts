export function getAllWallpapers(): Wallpaper[] {
  return WALLPAPERS;
}

export function getWallpaperBySlug(slug: string): Wallpaper | undefined {
  return WALLPAPERS.find((w) => w.slug === slug);
}

export function getWallpapersByCategory(category: string): Wallpaper[] {
  if (!category || category === 'all') return WALLPAPERS;
  return WALLPAPERS.filter((w) => w.category === category);
}

export function getRelatedWallpapers(currentSlug: string, limit = 4): Wallpaper[] {
  const current = getWallpaperBySlug(currentSlug);
  if (!current) return WALLPAPERS.slice(0, limit);
  return WALLPAPERS
    .filter((w) => w.slug !== currentSlug && (w.category === current.category || w.game === current.game))
    .slice(0, limit);
}

/**
 * Lấy URL ảnh xem trước chuẩn Cloudinary CDN (hoặc fallback về /wallpapers/ cục bộ)
 */
export function getWallpaperUrl(fileName: string): string {
  if (cloudinaryMap[fileName]) {
    return cloudinaryMap[fileName];
  }
  return `/wallpapers/${encodeURIComponent(fileName)}`;
}

/**
 * Lấy URL tải xuống trực tiếp từ Cloudinary CDN đính kèm attachment header
 */
export function getWallpaperDownloadUrl(fileName: string): string {
  const url = getWallpaperUrl(fileName);
  if (url.includes('res.cloudinary.com') && url.includes('/image/upload/')) {
    return url.replace('/image/upload/', '/image/upload/fl_attachment/');
  }
  return url;
}

/**
 * Lấy URL đầy đủ (tuyệt đối) phục vụ cho Schema.org, OpenGraph và Sitemap
 */
export function getWallpaperFullUrl(fileName: string, baseUrl = 'http://localhost:3000'): string {
  const url = getWallpaperUrl(fileName);
  if (url.startsWith('http://') || url.startsWith('https://')) {
    return url;
  }
  return `${baseUrl.replace(/\/$/, '')}${url.startsWith('/') ? '' : '/'}${url}`;
}

